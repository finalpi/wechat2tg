/* eslint-disable @typescript-eslint/no-var-requires */
/* global document,localStorage,window */
const assert = require('node:assert/strict')
const fs = require('node:fs'),path = require('node:path')
const {once} = require('node:events')
const {chromium} = require('playwright-core')
const {createDemoWebUI} = require('../dist/webui/dev')

async function main() {
  const preview = await createDemoWebUI('synthetic-demo-browser-token')
  preview.server.listen(0,'127.0.0.1');await once(preview.server,'listening')
  const origin = `http://127.0.0.1:${preview.server.address().port}`
  let browser
  try {
    const executablePath = process.env.BROWSER_EXECUTABLE_PATH || ['/usr/bin/chromium','/usr/bin/google-chrome','/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(file=>fs.existsSync(file))
    browser = await chromium.launch({executablePath,headless:true})
    const context = await browser.newContext({viewport:{width:1440,height:1000}})
    await context.addInitScript(token=>localStorage.setItem('webui-access-token',token),preview.token)
    const page = await context.newPage(),errors = [],external = []
    page.on('pageerror',error=>errors.push(error.message))
    await context.route('**/*',route=>{
      if(!route.request().url().startsWith(origin)){external.push(route.request().url());return route.abort()}
      return route.continue()
    })
    page.setDefaultTimeout(10000)
    page.on('dialog',dialog=>dialog.accept())
    await page.goto(origin + '/chat')
    await page.getByRole('alert',{name:'演示模式'}).waitFor()
    assert.equal(await page.getByRole('button',{name:'连接状态',exact:true}).innerText(),'🧪')
    await page.getByRole('button',{name:'产品讨论组',exact:true}).click()
    const imageRow = page.locator('[data-slot="message"]').filter({has:page.getByText('这是一张本地生成的示例图片。',{exact:true})})
    await imageRow.getByRole('button',{name:'查看',exact:true}).click()
    await page.getByRole('button',{name:'预览 周末山景.png',exact:true}).waitFor()
    await page.waitForFunction(()=>[...document.querySelectorAll('.chat-message-group [role="img"] img')].some(image=>image.complete && image.naturalWidth === 96))
    await page.getByRole('button',{name:'加载更早消息',exact:true}).click()
    await page.getByRole('button',{name:'加载更早消息',exact:true}).waitFor({state:'detached'})
    await page.getByLabel('消息内容',{exact:true}).fill('我正在预览，不会发给真实联系人')
    await page.getByRole('button',{name:'发送',exact:true}).click()
    const sentRow = page.locator('[data-slot="message"]').filter({has:page.getByText('我正在预览，不会发给真实联系人',{exact:true})})
    await sentRow.waitFor()
    await sentRow.hover()
    await sentRow.getByRole('button',{name:'消息操作',exact:true}).click()
    await sentRow.getByRole('button',{name:'撤回',exact:true}).click()
    await page.getByText('这条演示消息已撤回',{exact:true}).waitFor()
    const pending = page.locator('[data-slot="message"]').filter({has:page.getByText('这条是「同步结果未知」的演示，可以悬停后模拟重试。',{exact:true})})
    await pending.hover()
    await pending.getByRole('button',{name:'消息操作',exact:true}).click()
    await pending.getByRole('button',{name:'同步 Telegram',exact:true}).click()
    await pending.getByRole('button',{name:'同步 Telegram',exact:true}).waitFor({state:'detached'})
    await page.getByRole('button',{name:'成员',exact:true}).click()
    await page.getByRole('checkbox',{name:'林小满',exact:true}).check()
    await page.getByLabel('消息内容',{exact:true}).fill('成员选择也可以预览')
    await page.getByRole('button',{name:'发送',exact:true}).click()
    await page.getByText('@林小满 成员选择也可以预览',{exact:true}).waitFor()
    if(process.env.DEMO_SCREENSHOT_DIR){fs.mkdirSync(process.env.DEMO_SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.DEMO_SCREENSHOT_DIR,'desktop.png')})}
    await page.getByLabel('选择附件',{exact:true}).setInputFiles({name:'demo.txt',mimeType:'text/plain',buffer:Buffer.from('demo')})
    await page.getByRole('button',{name:'发送',exact:true}).click()
    await page.getByText('演示模式不支持上传附件或修改服务配置；可以预览示例附件、模拟发送文字。',{exact:false}).waitFor()
    assert(await page.getByRole('alert',{name:'演示模式'}).isVisible(),'blocked demo capabilities must not log the user out')
    await page.getByRole('button',{name:'移除附件',exact:true}).click()
    await page.getByRole('tab',{name:'通讯录',exact:true}).click()
    await page.getByRole('button',{name:'分类：公众号',exact:true}).click()
    await page.getByRole('button',{name:'设计周刊',exact:true}).waitFor()
    await page.getByRole('button',{name:'聊天菜单',exact:true}).click()
    await page.getByRole('button',{name:'管理设置',exact:true}).click()
    await page.getByText('🧪 演示预览：服务配置只读，不调用真实服务；「聊天界面」显示偏好仍可调整。',{exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:'保存',exact:true}).count(),0)
    await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'聊天界面',exact:true}).click()
    await page.getByRole('button',{name:'隐藏公众号',exact:true}).click()
    await page.getByRole('button',{name:'返回聊天',exact:true}).click()
    assert.equal(await page.getByRole('button',{name:'分类：公众号',exact:true}).count(),0)
    const mobileContext = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
    await mobileContext.addInitScript(token=>localStorage.setItem('webui-access-token',token),preview.token)
    const mobile = await mobileContext.newPage()
    mobile.on('pageerror',error=>errors.push(error.message))
    await mobile.goto(origin + '/chat')
    await mobile.getByRole('button',{name:'产品讨论组',exact:true}).click()
    assert(await mobile.getByRole('alert',{name:'演示模式'}).isVisible())
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth))
    if(process.env.DEMO_SCREENSHOT_DIR)await mobile.screenshot({path:path.join(process.env.DEMO_SCREENSHOT_DIR,'mobile.png')})
    assert.deepEqual(errors,[])
    assert.deepEqual(external,[],'preview makes no external browser requests')
    console.log('Demo browser passed: explicit mock banner, local avatars/media, history, simulated send/recall/sync/mentions, read-only configuration, visibility preview, touch layout; no real service calls.')
  } finally {if(browser)await browser.close();await preview.dispose()}
}
main().catch(error=>{console.error(error);process.exitCode = 1})