async function fixture(t) {
  const store = new WebMessageStore(':memory:')
  t.after(() => store.close())
  await store.all('SELECT 1')
  const events = []
  const unsubscribe = store.subscribe(event => events.push(event))
  t.after(unsubscribe)
  return {store, events, unsubscribe}
}
const message = (remoteId, extra = {}) => ({wxId: 'peer', remoteId, body: 'private message', direction: 'incoming', type: 'text', status: 'received', timestamp: 1, ...extra})
const changed = (id, wxId = 'peer') => ({type: 'messages', wxId, ids: [id]})
const clear = events => {events.length = 0}

test('successful inserts and raw updates publish committed IDs, including old rows', async t => {
  const {store, events} = await fixture(t)
  const reads = []
  store.subscribe(event => {if (event.ids) reads.push(store.byId(event.ids[0]))})
  const old = await store.insert(message('1', {source: 'private protocol credentials', details: '{"title":"private title"}'}))
  assert.deepEqual(events, [changed(old.id)])
  for (let i = 2; i < 55; i++) await store.insert(message(String(i), {timestamp: i}))
  clear(events)
  await store.run('UPDATE inbox SET status=?,telegramStatus=? WHERE id=?', ['submitted', 'failed', old.id])
  assert.deepEqual(events, [changed(old.id)])
  const observed = await Promise.all(reads)
  assert.equal(observed.at(-1).telegramStatus, 'failed')
  assert(!JSON.stringify(events).includes('private'))
  assert.deepEqual(Object.keys(events[0]).sort(), ['ids', 'type', 'wxId'])
})

test('SELECTs, cache writes, ignored/unchanged updates and failed writes stay silent', async t => {
  const {store, events} = await fixture(t)
  const row = await store.insert(message('1'))
  clear(events)
  await store.all('SELECT * FROM inbox')
  await store.history('peer')
  await store.run('SELECT * FROM inbox')
  await store.run('INSERT INTO media(id,name) VALUES(?,?)', ['cached', 'private.bin'])
  await store.run('UPDATE media SET name=? WHERE id=?', ['other.bin', 'cached'])
  await store.run('INSERT INTO transcript_media(cacheKey,attachmentId) VALUES(?,?)', ['private-key', 'cached'])
  await store.run('DELETE FROM media WHERE id=?', ['cached'])
  await store.insert(message('1'))
  await store.run('UPDATE inbox SET body=body,source=source,details=details,telegramStatus=telegramStatus WHERE id=?', [row.id])
  await store.run('UPDATE inbox SET status=? WHERE id=?', ['failed', 987654])
  await assert.rejects(store.run('UPDATE inbox SET body=NULL WHERE id=?', [row.id]), /SQLITE_CONSTRAINT/)
  await assert.rejects(store.run('INSERT INTO inbox(wxId,body) VALUES(?,?)', ['peer', 'invalid']), /SQLITE_CONSTRAINT/)
  await assert.rejects(store.run('UPDATE missing_table SET status=1'), /SQLITE_ERROR/)
  await store.run('UPDATE inbox SET source=source')
  assert.deepEqual(events, [])
  assert.equal((await store.byId(row.id)).body, 'private message')
  await store.run('UPDATE inbox SET source=? WHERE id=?', ['changed receipt affects revoke eligibility', row.id])
  assert.deepEqual(events, [changed(row.id)], 'source-only receipt repairs can change visible capabilities, but never expose source')
})

