test('stores do not share a bus, even when connected to the same SQLite file', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'wx2tg-message-events-'))
  const file = path.join(directory, 'messages.db')
  const first = new WebMessageStore(file)
  await first.all('SELECT 1')
  const second = new WebMessageStore(file)
  await second.all('SELECT 1')
  t.after(async () => {await first.close(); await second.close(); fs.rmSync(directory, {recursive: true, force: true})})
  const a = [], b = [], shared = []
  const stopA = first.subscribe(event => a.push(event))
  const stopB = second.subscribe(event => b.push(event))
  const stopShared = messageEvents.subscribe(event => shared.push(event))
  t.after(() => {stopA(); stopB(); stopShared()})
  await first.insert(message('1'))
  assert.equal(a.length, 1)
  assert.deepEqual(b, [])
  assert.deepEqual(shared, [])
  await second.insert(message('2'))
  assert.equal(a.length, 1)
  assert.equal(b.length, 1)
  stopA(); stopA()
  await first.insert(message('3'))
  assert.equal(a.length, 1)
  assert.equal(b.length, 1)
})

test('bus isolates throws/rejections/mutations and cleans up independent subscriptions', async () => {
  const bus = createMessageEvents(), events = []
  const listener = event => events.push(event)
  bus.subscribe(() => {throw new Error('broken listener')})
  bus.subscribe(async () => {throw new Error('broken async listener')})
  bus.subscribe(event => {event.ids?.push(999)})
  const first = bus.subscribe(listener), second = bus.subscribe(listener)
  const input = {type: 'messages', wxId: 'peer', ids: [1, 1, 2], source: 'must not escape', body: 'must not escape'}
  bus.publish(input)
  input.ids.push(3)
  assert.deepEqual(events, [{type: 'messages', wxId: 'peer', ids: [1, 2]}, {type: 'messages', wxId: 'peer', ids: [1, 2]}])
  first(); first()
  bus.publish({type: 'status'})
  assert.equal(events.length, 3)
  second()
  bus.publish({type: 'contacts'})
  assert.equal(events.length, 3)
  const bounded = []
  bus.subscribe(event => bounded.push(event))
  bus.publish({type: 'messages', wxId: 'peer', ids: Array.from({length: 101}, (_, i) => i + 1)})
  assert.deepEqual(bounded, [{type: 'messages', wxId: 'peer'}])
  await new Promise(resolve => setImmediate(resolve))
})

