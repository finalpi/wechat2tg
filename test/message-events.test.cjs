test('updates retrieves only requested visible conversation rows, enriches and omits source/context metadata', async t => {
  const {createMessageCenter} = require('../dist/webui/messages')
  const {AppDataSource} = require('../dist/data-sourse')
  t.mock.method(AppDataSource, 'getRepository', () => ({findOneBy: async ({wxId}) => wxId === 'peer' ? {wxId} : null}))
  const {store, events} = await fixture(t)
  const old = await store.insert(message('1', {source: '{"private":"credentials"}', details: '{"title":"saved detail"}'}))
  const foreign = await store.insert(message('2', {wxId: 'other'}))
  const hidden = await store.insert(message('3'))
  await store.run('UPDATE inbox SET hidden=1 WHERE id=?', [hidden.id])
  for (let i = 4; i < 60; i++) await store.insert(message(String(i), {timestamp: i}))
  await store.run('UPDATE inbox SET telegramStatus=? WHERE id=?', ['synced', old.id])
  const center = createMessageCenter(store, {})
  clear(events)
  const result = await center.updates('peer', [old.id, foreign.id, hidden.id, 99999, old.id])
  assert.deepEqual(Object.keys(result).sort(), ['messages', 'serverTime'])
  assert.equal(result.messages.length, 1)
  assert.equal(result.messages[0].id, old.id)
  assert.equal(result.messages[0].telegramStatus, 'synced')
  assert.deepEqual(result.messages[0].details, {title: 'saved detail'})
  assert.equal(typeof result.messages[0].canRevoke, 'boolean')
  assert.equal(typeof result.messages[0].senderDisplayName, 'string')
  assert.equal(typeof result.serverTime, 'number')
  assert(!JSON.stringify(result).includes('credentials'))
  assert.equal('source' in result.messages[0], false)
  assert.deepEqual(events, [])
  assert.deepEqual((await center.updates('peer', [foreign.id])).messages, [])
  await assert.rejects(center.updates('unknown', [old.id]), error => error.code === 'recipientMissing')
  for (const ids of [[], [0], [-1], [1.1], ['1'], [NaN], Array.from({length: 101}, () => 1)]) {
    await assert.rejects(center.updates('peer', ids), error => error.code === 'invalidRequest')
  }
  await assert.rejects(center.updates('', [old.id]), error => error.code === 'invalidRequest')
})