test('hidden-only writes are silent, visibility/ownership changes and deletes identify affected rows', async t => {
  const {store, events} = await fixture(t)
  const id = await store.run('INSERT INTO inbox(wxId,remoteId,body,direction,type,status,timestamp,hidden) VALUES(\'peer\',\'1\',\'hidden\',\'incoming\',\'text\',\'received\',1,1)')
  await store.run('UPDATE inbox SET body=? WHERE id=?', ['still hidden', id])
  assert.deepEqual(events, [])
  await store.run('UPDATE inbox SET hidden=0 WHERE id=?', [id])
  assert.deepEqual(events, [changed(id)])
  clear(events)
  await store.run('UPDATE inbox SET wxId=? WHERE id=?', ['other', id])
  assert.deepEqual(events, [changed(id, 'other'), changed(id)])
  clear(events)
  await store.run('UPDATE inbox SET hidden=1 WHERE id=?', [id])
  assert.deepEqual(events, [changed(id, 'other')])
  clear(events)
  await store.run('DELETE FROM inbox WHERE id=?', [id])
  assert.deepEqual(events, [])
  const visible = await store.insert(message('2'))
  clear(events)
  await store.run('DELETE FROM inbox WHERE id=?', [visible.id])
  assert.deepEqual(events, [changed(visible.id)])
})

test('sync/revoke claims keep their atomic result and publish only real transitions', async t => {
  const {store, events} = await fixture(t)
  const row = await store.insert(message('1', {telegramStatus: 'pending'}))
  clear(events)
  assert.deepEqual(await Promise.all([store.claimSync(row.id), store.claimSync(row.id)]), [true, false])
  assert.deepEqual(events, [changed(row.id)])
  await store.setTelegramStatus('1', 'synced')
  assert.deepEqual(events, [changed(row.id), changed(row.id)])
  clear(events)
  await store.setTelegramStatus('1', 'synced')
  assert.equal(await store.claimSync(row.id), false)
  assert.equal(await store.claimSync(99999), false)
  assert.deepEqual(events, [])
  assert.equal(await store.claimRevoke(row.id, 'request-one'), true)
  assert.equal(await store.claimRevoke(row.id, 'request-one'), false)
  assert.deepEqual(events, [changed(row.id)])
  const other = await store.insert(message('2'))
  clear(events)
  await assert.rejects(store.claimRevoke(other.id, 'request-one'), /SQLITE_CONSTRAINT/)
  assert.deepEqual(events, [])
  assert.equal(await store.claimRevoke(other.id, 'request-two'), true)
  assert.deepEqual(events, [changed(other.id)])
})

