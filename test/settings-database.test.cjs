/* eslint-disable @typescript-eslint/no-var-requires */
const {test} = require('node:test'),assert = require('node:assert/strict')
const fs = require('node:fs'),os = require('node:os'),path = require('node:path'),{once} = require('node:events')
const {Database} = require('sqlite3')
const {SettingsDatabase,environmentOverrides} = require('../dist/webui/settings-db')
const {createWebUIServer} = require('../dist/webui/server')
const {TelegramDisplayPolicy} = require('../dist/util/TelegramDisplayPolicy')
const {AutomationEngine} = require('../dist/automation/engine')
const {McpSettings} = require('../dist/mcp/settings')

function fixture(t){
  const root = fs.mkdtempSync(path.join(os.tmpdir(),'unified-settings-'))
  t.after(()=>fs.rmSync(root,{force:true,recursive:true}))
  const dbFile = path.join(root,'db','wx2tg.db'),legacy = path.join(root,'custom','webui.json')
  fs.mkdirSync(path.dirname(legacy),{recursive:true})
  return {root,dbFile,legacy,open:()=>SettingsDatabase.open(dbFile,legacy),put:(name,value,dir = path.dirname(legacy))=>fs.writeFileSync(path.join(dir,name),JSON.stringify(value))}
}
const run = (db,sql)=>new Promise((resolve,reject)=>db.run(sql,error=>error ? reject(error) : resolve()))
const get = (db,sql)=>new Promise((resolve,reject)=>db.get(sql,(error,row)=>error ? reject(error) : resolve(row)))
const close = db=>new Promise((resolve,reject)=>db.close(error=>error ? reject(error) : resolve()))

test('legacy configuration migrates once into the same SQLite file without touching existing rows or legacy files',async t=>{
  const f = fixture(t)
  fs.mkdirSync(path.dirname(f.dbFile))
  const old = new Database(f.dbFile)
  await run(old,'CREATE TABLE configuration (id INTEGER PRIMARY KEY, chatId INTEGER)')
  await run(old,'INSERT INTO configuration VALUES (1, 200)')
  await run(old,'CREATE TABLE bind_group (id INTEGER PRIMARY KEY, chatId INTEGER)')
  await run(old,'INSERT INTO bind_group VALUES (2, -100123)')
  await close(old)
  const custom = {AI_MODEL:'legacy-model',AUTO_CREATE_GROUPS:false,CONTACT_MESSAGE:'<b>my template</b>',MQTT_ENABLED:'false'}
  f.put('webui.json',custom)
  f.put('telegram-display.json',{version:1,botId:100,ownerId:200,global:'enhanced',chats:{'-100123':'compatible'}},f.root)
  f.put('automations.json',{format:1,scripts:[],rules:[],runs:[],samples:[],claims:{},values:{}})
  f.put('mcp-settings.json',{enabled:false,endpoint:'',scriptPath:'/path/to/bridge',write:'w'.repeat(32),read:'r'.repeat(32)})
  fs.writeFileSync(path.join(path.dirname(f.legacy),'webui-token'),'legacy-webui-token\n')
  let db = await f.open()
  try {
    assert.deepEqual(db.savedEnvironment(),{...custom,AUTO_CREATE_GROUPS:'false'})
    assert.equal(db.document('webui-token').read(),'legacy-webui-token')
    assert.equal(new McpSettings(path.join(f.root,'unused.json'),undefined,db).metadata().scriptPath,'/path/to/bridge')
    const engine = new AutomationEngine('unused',undefined,undefined,db.document('automations'))
    await engine.command({revision:(await engine.snapshot()).revision,operation:'saveScript',script:{name:'migrated',source:'() => ({})'}})
    const display = new TelegramDisplayPolicy('unused','auto',undefined,db)
    display.configure(100,200)
    assert.equal(display.mode(), 'enhanced')
    assert.equal(display.mode(-100123), 'compatible')
    await display.setMode('inherit',-100123)
    display.configure(101,200)
    assert.equal(display.mode(), 'auto')
    await db.saveEnvironment({...db.savedEnvironment(),AI_MODEL:'new-db-model'})
  } finally {await db.close()}
  assert.deepEqual(JSON.parse(fs.readFileSync(f.legacy,'utf8')),custom)
  f.put('webui.json',{AI_MODEL:'stale-json'})
  db = await f.open()
  try {
    assert.equal(db.savedEnvironment().AI_MODEL,'new-db-model')
    assert.equal(JSON.parse(db.document('automations').read()).scripts[0].name,'migrated')
    const display = new TelegramDisplayPolicy('unused','auto',undefined,db,'compatible')
    display.configure(100,200)
    assert.deepEqual(display.overrideSnapshot().chats,{})
    assert.equal(display.overrideSnapshot().global,'enhanced')
    assert.equal(display.mode(),'compatible')
    assert.equal(fs.statSync(f.dbFile).mode & 0o777,0o600)
  } finally {await db.close()}
  const check = new Database(f.dbFile)
  assert.equal((await get(check,'SELECT chatId FROM configuration')).chatId,200)
  assert.equal((await get(check,'SELECT chatId FROM bind_group')).chatId,-100123)
  await close(check)
})

test('invalid legacy input aborts migration and can be retried without importing a partial snapshot',async t=>{
  const f = fixture(t)
  fs.writeFileSync(f.legacy,'{broken')
  await assert.rejects(f.open())
  assert.equal(fs.readFileSync(f.legacy,'utf8'),'{broken')
  const check = new Database(f.dbFile)
  assert.equal((await get(check,'SELECT count(*) AS count FROM app_settings')).count,0)
  await close(check)
  f.put('webui.json',{AI_MODEL:'corrected'})
  const db = await f.open()
  assert.equal(db.savedEnvironment().AI_MODEL,'corrected')
  await db.close()
})

test('WebUI saves the SQLite value under an ENV override without echoing or persisting the override',async t=>{
  const f = fixture(t)
  f.put('webui.json',{AI_MODEL:'saved-before',AI_API_KEY:'legacy-synthetic-secret'})
  const db = await f.open()
  const token = 'synthetic-config-token',envOverrides = environmentOverrides({AI_MODEL:'env-active',AI_API_KEY:'env-only-secret',BOT_TOKEN:'',WEBUI_PORT:'6000'})
  assert.deepEqual(envOverrides,{AI_MODEL:'env-active',AI_API_KEY:'env-only-secret'})
  const display = new TelegramDisplayPolicy('unused','auto',undefined,db)
  display.configure(100,200)
  const server = createWebUIServer({environment:{AI_MODEL:'env-active',AI_API_KEY:'env-only-secret'},envOverrides,database:db,token,display})
  server.listen(0,'127.0.0.1');await once(server,'listening')
  t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await db.close()})
  const request = async (url,body,auth = token)=>{
    const res = await fetch(`http://127.0.0.1:${server.address().port}${url}`,{method:body ? 'PATCH' : 'GET',headers:{authorization:`Bearer ${auth}`,'content-type':'application/json'},body:body && JSON.stringify(body)})
    return {status:res.status,data:await res.json()}
  }
  const {data:before} = await request('/api/config')
  assert.equal(before.values.AI_MODEL,'saved-before')
  assert.equal(before.values.AI_API_KEY,'')
  assert.ok(before.secrets.AI_API_KEY)
  assert.deepEqual(new Set(before.envOverridden),new Set(['AI_MODEL','AI_API_KEY']))
  assert.equal(before.restartRequired,false)
  const {status,data} = await request('/api/config',{revision:before.revision,source:'environment',values:{AI_MODEL:'saved-after'}})
  assert.equal(status,200)
  assert.equal(data.restartRequired,false)
  assert.deepEqual(db.savedEnvironment(),{AI_MODEL:'saved-after',AI_API_KEY:'legacy-synthetic-secret'})
  assert.equal(await db.importEnvironment({AI_MODEL:'do-not-replace',BASE_API:'http://wx2tg-server:8058/api',WEBUI_PORT:'6000'}),1)
  assert.equal(db.savedEnvironment().BASE_API,'http://wx2tg-server:8058/api')
  assert.equal(db.savedEnvironment().WEBUI_PORT,undefined)
  const route = '/api/config/telegram-display'
  assert.equal((await request(route,undefined,'not-admin')).status,401)
  const prefs = (await request(route)).data
  assert.equal((await request(route,{revision:prefs.revision,chatId:-100123,mode:'compatible'})).status,200)
  assert.equal(display.mode(-100123),'compatible')
  assert.equal((await request(route,{revision:prefs.revision,chatId:-100123,mode:'enhanced'})).status,409)
})