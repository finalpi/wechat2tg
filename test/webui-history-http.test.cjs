/* eslint-disable @typescript-eslint/no-var-requires */
require('reflect-metadata')
const {test} = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const {once} = require('node:events')
const {DataSource} = require('typeorm')
const {Message} = require('../dist/entity/Message')
const {BindGroup} = require('../dist/entity/BindGroup')
const {AppDataSource} = require('../dist/data-sourse')
const {AbstractClient} = require('../dist/base/BaseClient')
const {WebMessageStore} = require('../dist/webui/message-store')
const {createMessageCenter} = require('../dist/webui/messages')
const {createWebUIServer} = require('../dist/webui/server')

for (const wxId of ['synthetic@chatroom', 'gh_synthetic']) test(`HTTP history merges real SQLite records without returning 500: ${wxId}`, async t => {
  const db = new DataSource({type: 'sqlite', database: ':memory:', entities: [Message, BindGroup], synchronize: true})
  await db.initialize()
  t.after(() => db.destroy())
  // Real repositories, SQL and adapter; only live account collaborators are isolated.
  t.mock.method(AppDataSource, 'getRepository', entity => db.getRepository(entity))
  t.mock.method(AbstractClient, 'getSpyClient', () => undefined)
  await db.getRepository(BindGroup).save({wxId, chatId: -10001, type: wxId.endsWith('@chatroom') ? 1 : 0, name: 'Synthetic'})
  await db.getRepository(Message).save({chatId: -10001, wxMsgId: '123', content: 'Synthetic message', type: 0, createTime: 100, tgBotMsgId: 1})
  const store = new WebMessageStore(':memory:')
  t.after(() => store.close())
  const row = await store.insert({wxId, remoteId: '123', body: 'Synthetic message', type: 'text', direction: 'incoming', status: 'received', timestamp: 100, bodyFormat: 'plain'})
  const events = [], stop = store.subscribe(event => events.push(event))
  t.after(stop)
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'history-http-'))
  const server = createWebUIServer({environment: {}, token: 'synthetic-token', file: path.join(directory, 'webui.json'), messages: createMessageCenter(store, {}), mcpTokens: {write: 'w'.repeat(32), read: 'r'.repeat(32)}})
  server.listen(0, '127.0.0.1'); await once(server, 'listening')
  t.after(async () => {server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); fs.rmSync(directory, {recursive: true})})
  const url = `http://127.0.0.1:${server.address().port}/api/messages?wxId=${encodeURIComponent(wxId)}&q=&before=0`
  const request = () => fetch(url, {headers: {Authorization: 'Bearer synthetic-token'}})
  const response = await request()
  assert.equal(response.status, 200, 'first read must merge existing plain rows into Telegram history without a trigger conflict')
  const result = await response.json()
  assert.equal(result.messages.length, 1)
  assert.equal(result.messages[0].id, row.id)
  assert.equal(result.messages[0].bodyFormat, 'telegram_html')
  assert.equal('source' in result.messages[0], false)
  assert(events.some(event => event.ids?.includes(row.id)))
  events.length = 0
  assert.equal((await request()).status, 200)
  assert.deepEqual(events, [], 'subsequent history reads must not create a notification loop')
})